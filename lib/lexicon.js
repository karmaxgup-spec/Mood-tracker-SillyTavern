/**
 * Build a phrase lookup map from lexicon entries.
 * Inputs: entries (LexEntry[]). Output: Map<phrase, {emotion, weight}>.
 * Side effects: none. Duplicate phrases keep the higher weight.
 * @param {LexEntry[]} entries
 * @returns {Map<string, {emotion: string, weight: number}>}
 */
export function buildPhraseMap(entries) {
  const map = new Map();
  for (const e of entries) {
    const key = e.phrase.toLowerCase();
    const prev = map.get(key);
    if (!prev || e.weight > prev.weight) {
      map.set(key, { emotion: e.emotion, weight: e.weight });
    }
  }
  return map;
}
